def words() -> list[str]:
    """全部词，按长度降序，供最长匹配。"""
    return sorted({row[0] for row in SPIRIT_DICT}, key=len, reverse=True)


def lookup(word: str):
    """按词查询，返回 dict 或 None。"""
    for row in SPIRIT_DICT:
        if row[0] == word:
            return dict(
                word=row[0],
                category=row[1],
                cluster=row[2],
                sentiment=row[3],
                scale=row[4],
                scale_basis=row[5],
            )
    return None


def clusters() -> dict[str, list[str]]:
    """五大情感簇→成员词列表（不含无簇词条）。"""
    result: dict[str, list[str]] = {name: [] for name in CLUSTERS}
    for row in SPIRIT_DICT:
        if row[2] is not None:
            result[row[2]].append(row[0])
    return result


