def words() -> list[str]:
    """全部词条（长词优先，供最长匹配扫描）。"""
    return sorted({row[0] for row in COLOR_DICT}, key=lambda w: (-len(w), w))


def lookup(word: str):
    """查询单个色彩词，返回 dict 或 None。"""
    for row in COLOR_DICT:
        if row[0] == word:
            return dict(word=row[0], family=row[1], hex=row[2],
                        brightness=row[3], reason=row[4])
    return None


if __name__ == "__main__":
    import re
    import sys

    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

    errors = []
    seen = set()
    hex_pat = re.compile(r"^#[0-9A-F]{6}$")
    for row in COLOR_DICT:
        if len(row) != 5:
            errors.append(f"字段数不为5: {row!r}")
            continue
        w, fam, hx, br, reason = row
        if w in seen:
            errors.append(f"重复词条: {w}")
        seen.add(w)
        if fam not in FAMILIES:
            errors.append(f"未知色系 {fam!r}: {w}")
        if not hex_pat.match(hx):
            errors.append(f"非法色值 {hx!r}: {w}")
        if br not in BRIGHTNESS_LEVELS:
            errors.append(f"非法明度档 {br!r}: {w}")
        if not reason:
            errors.append(f"缺归属理由: {w}")
    for ex in EXCLUDE_WORDS:
        if ex in seen:
            errors.append(f"屏蔽词不应同时是词条: {ex}")

    print(f"词条数: {len(COLOR_DICT)} (目标>=60)")
    print(f"色系分布: {[ (f, sum(1 for r in COLOR_DICT if r[1]==f)) for f in FAMILIES ]}")
    print(f"屏蔽词数: {len(EXCLUDE_WORDS)}")
    print(f"lookup('黛') -> {lookup('黛')}")
    print(f"lookup('惨绿') -> {lookup('惨绿')}")
    print(f"lookup('不存在') -> {lookup('不存在')}")
    if len(COLOR_DICT) < 60:
        errors.append(f"词条数 {len(COLOR_DICT)} < 60")
    if errors:
        print("自检失败:")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    print("自检通过 OK")
