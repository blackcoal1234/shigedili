CATEGORIES = ("孤独", "自称", "他称")


def words() -> list[str]:
    """全部词条，按长度降序（供最长优先匹配使用）。"""
    return sorted({row[0] for row in SOLITUDE_DICT}, key=len, reverse=True)


def lookup(word: str):
    for row in SOLITUDE_DICT:
        if row[0] == word:
            return dict(word=row[0], category=row[1], intensity=row[2])
    return None


def by_category(category: str) -> list[tuple[str, float]]:
    return [(w, s) for w, c, s in SOLITUDE_DICT if c == category]


