"""人称与孤独感词典：词 → 类别 + 强度。

风格计量（stylometry）"人称与孤独感"维度的人工词典，由本课程项目人工整理，
参考古典诗词赏析的常见口径整理词条，分三类：

- 孤独：直接或高度惯用地表达孤独、孤寂处境的字词（独、孤、寂、寞、无人、
        空……）。强度 [0, 1] 表示"孤独感浓度"：复合词（独酌、孤灯、寂寞）
        语义专一，强度高；单字兜底词强度低。
- 自称：第一人称自我指称（我、吾、余、予、身……）。强度表示该词落在诗句中
        确为自称的可靠度（多义字打低分）。
- 他称：第二/第三人称他者指称（君、尔、汝、谁、故人、客……）。强度同为
        指称可靠度。自称/他称之比用于区分"独白型"与"对话型"诗人。

多义字口径（重要，均按"宁低勿高"原则打权重）：
- "空"：兼有天空/空间（空中、晴空）、徒然（空自）、空寂（空山、空房）三路
  含义，单字仅给 0.25 兜底；孤独义主要由"空床/空房/空庭"等复合词承担。
- "自"：按任务口径归入孤独词（取"花自飘零""自去自来"中的"独自"义），但
  "自古/自从/自然"等虚词用法极多，仅给 0.15，防止淹没统计。
- "余/予"：既是自称又常作"剩余/给予"义，各给 0.5。
- "身"：此身/吾身为自称，终身/身后偏泛指，给 0.6；"此身"单列 1.0。
- "客"：既指他者（宾客、行客），也常是诗人自况（独在异乡为异客），按任务
  口径归他称，给 0.5。
- "君/郎/卿"：多为面称（他称），但"君王/周郎"等偏第三人称专名，权重按
  惯用度折中。
- "妾/老夫/我辈"为超出任务最小清单的自称补充，为覆盖李清照、苏轼等诗人的
  惯用自称而加入，已在此说明。

本词典是人工整理的分析工具，不是外部权威词库或模型输出；一切统计结论只在
本词典口径内成立。

匹配约定：扫描按"最长优先、不重叠"贪心匹配——"独自"计 1 次复合词，不再
重复计"独"和"自"；词条不含标点，匹配天然不跨句读。
"""

