# 已知一词多义误报：匹配前先从文本中挖除这些片段（不计入任何词条）。
EXCLUDE_PATTERNS = [
    "萧瑟",      # 萧瑟=凋敝萧条，其"瑟"非乐器
    "瑟缩",      # 瑟缩=蜷缩
    "半江瑟瑟",  # 暮江吟"半江瑟瑟半江红"：瑟瑟作碧色解，非风声
    "杜鹃花",  # 花名，非鸟啼
    "钟山",    # 地名
    "钟情",    # 钟=聚集
    "屋漏",    # 床头屋漏：漏雨非更漏（词典未收单字"漏"，防御性保留）
]

VALID_CATEGORIES = ("兽鸣", "鸟啼", "器乐", "钟磬", "自然声", "人声")
VALID_KINDS = ("源", "动", "拟声")


def words() -> list[str]:
    """全部词条，按长度降序（供最长优先匹配）。"""
    return sorted({row[0] for row in SOUND_DICT}, key=len, reverse=True)


def lookup(word: str):
    """按词查询，返回 dict 或 None。"""
    for row in SOUND_DICT:
        if row[0] == word:
            return dict(word=row[0], category=row[1], sentiment=row[2],
                        kind=row[3], note=row[4])
    return None


def _selfcheck() -> None:
    n = len(SOUND_DICT)
    assert n >= 50, f"词条数 {n} < 50"
    seen = set()
    for w, cat, sent, kind, note in SOUND_DICT:
        assert w not in seen, f"重复词条: {w}"
        seen.add(w)
        assert cat in VALID_CATEGORIES, f"{w}: 非法类别 {cat}"
        assert kind in VALID_KINDS, f"{w}: 非法词性 {kind}"
        assert -1.0 <= sent <= 1.0, f"{w}: 情感越界 {sent}"
        assert isinstance(note, str) and note, f"{w}: 缺简注"
    assert lookup("猿")["category"] == "兽鸣"
    assert lookup("砧")["category"] == "人声"
    assert lookup("不存在的词") is None
    from collections import Counter
    dist = Counter(row[1] for row in SOUND_DICT)
    print(f"sound_dict 自检通过：{n} 词条，类别分布 {dict(dist)}")


if __name__ == "__main__":
    _selfcheck()
