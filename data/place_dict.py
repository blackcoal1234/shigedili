def aliases() -> list[str]:
    """返回按长度倒序排列的古名列表，用于贪心匹配避免短名先吞。"""
    return sorted({row[0] for row in PLACE_DICT}, key=len, reverse=True)


def lookup(alias: str):
    for row in PLACE_DICT:
        if row[0] == alias:
            return dict(alias=row[0], modern=row[1], province=row[2],
                        lon=row[3], lat=row[4], note=row[5])
    return None
