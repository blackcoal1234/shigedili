"""古典诗词细粒度情感本体（模型辅助整理、规则化发布）。

本模块把诗歌情感拆成三层：

1. 连续维度：valence（愉悦度，-1..1）、arousal（唤醒度，0..1）、
   dominance（掌控感，-1..1）；结构参考 NRC-VAD 的 VAD 表达方式。
2. 多标签情绪：24 类可并存的古典诗词语境标签，不强迫一首诗只有一种情感。
3. 文学形容词：用于页面叙事的可读描述，例如「苍凉、幽愤、激切」。

词条候选由语言模型依据古典诗词常见赏析语汇扩充，再按项目 1772 首语料
做命中检查并收敛为可审计的本地规则。它不是权威情感词典，也不把词典命中
等同于作者真实心理。页面必须同时展示命中词与置信等级。

每个关键词为 (文字, 权重)。多字短语权重高于单字直接情绪词；分类器执行
最长词优先并处理常见否定前缀，减少「莫愁」「不悲」一类反向误判。
"""
